//词法/相邻 token 的切分矩阵:最长匹配、标识符与数字的边界、注释与字符串
import {describe, expect, it} from 'vitest'
import {lex_src} from './helper'

const values = (src: string) => lex_src(src).map((t: any) => t.value)

//[输入, 期望的 token 值序列]
const CASES: [string, string[]][] = [
    //标识符与数字的边界
    ['a+1', ['a', '+', '1']],
    ['a1', ['a1']],
    ['1a', ['1', 'a']],
    ['1e3a', ['1e3', 'a']],
    ['0x1f+1', ['0x1f', '+', '1']],
    ['0b101', ['0b101']],
    ['0o17', ['0o17']],
    ['1.', ['1', '.']],
    ['$x', ['$x']],
    ['a b', ['a', 'b']],

    //比较与移位:最长匹配
    ['a==b', ['a', '==', 'b']],
    ['a===b', ['a', '===', 'b']],
    ['a!=b', ['a', '!=', 'b']],
    ['a!==b', ['a', '!==', 'b']],
    ['a<b', ['a', '<', 'b']],
    ['a<=b', ['a', '<=', 'b']],
    ['a<<b', ['a', '<<', 'b']],
    ['a<<=b', ['a', '<<=', 'b']],
    ['a>b', ['a', '>', 'b']],
    ['a>=b', ['a', '>=', 'b']],
    ['a>>b', ['a', '>>', 'b']],
    ['a>>=b', ['a', '>>=', 'b']],

    //位运算与逻辑运算:一条边一个 token
    ['a&b', ['a', '&', 'b']],
    ['a&&b', ['a', '&&', 'b']],
    ['a&=b', ['a', '&=', 'b']],
    ['a&&=b', ['a', '&&=', 'b']],
    ['a|b', ['a', '|', 'b']],
    ['a||b', ['a', '||', 'b']],
    ['a|=b', ['a', '|=', 'b']],
    ['a||=b', ['a', '||=', 'b']],

    //前缀/后缀
    ['!a', ['!', 'a']],
    ['~a', ['~', 'a']],
    ['-a', ['-', 'a']],
    ['++a', ['++', 'a']],
    ['a++', ['a', '++']],
    ['--a', ['--', 'a']],
    ['a--', ['a', '--']],

    //算术与成员访问
    ['a*b', ['a', '*', 'b']],
    ['a/b', ['a', '/', 'b']],
    ['a%b', ['a', '%', 'b']],
    ['a.b', ['a', '.', 'b']],
    ['a[i]', ['a', '[', 'i', ']']],
    ['a?b:c', ['a', '?', 'b', ':', 'c']],
    ['a=b=c', ['a', '=', 'b', '=', 'c']],
    ['x:number', ['x', ':', 'number']],
    ['a->b', ['a', '-', '>', 'b']],

    //注释
    ['a/*c*/b', ['a', '/*c*/', 'b']],
    ['a//c', ['a', '//c']],

    //关键字与标识符的边界
    ['if(a)', ['if', '(', 'a', ')']],
    ['interface', ['interface']],
    ['in', ['in']],
    ['for(;;)', ['for', '(', ';', ';', ')']],
    ['new C()', ['new', 'C', '(', ')']],
    ['@T', ['@', 'T']],

    //字符串的三种引号与转义
    [`'a'`, ['a']],
    ['`a`', ['a']],
    ['"a"', ['a']],
    ['"a\\"b"', ['a"b']]
]

describe('lexer/相邻 token 切分矩阵', () => {
    for (const [src, want] of CASES)
        it(JSON.stringify(src), () => {
            expect(values(src)).toEqual(want)
        })

    it('标识符、运算符、数字是三种不同的 token 类型', () => {
        const types = lex_src('a+1').map((t: any) => t.type)
        expect(new Set(types).size).toBe(3)
    })

    it('标识符 e 后面跟运算符不会被当成指数', () => {
        expect(values('e+1')).toEqual(['e', '+', '1'])
        expect(values('a=e+1')).toEqual(['a', '=', 'e', '+', '1'])
        expect(values('x=E-2')).toEqual(['x', '=', 'E', '-', '2'])
    })

    it('科学计数法仍然是一个数字', () => {
        expect(values('1e3')).toEqual(['1e3'])
        expect(values('1.5e-2')).toEqual(['1.5e-2'])
        expect(values('2E+5')).toEqual(['2E+5'])
    })
})
